// Records each scene of the draft demo video from the public site with headless Chrome.
import { chromium } from 'playwright';
import fs from 'node:fs';

const BASE = 'https://wichai-pan.github.io/inside-the-game/';
const W = 1280, H = 800;
const dur = JSON.parse(fs.readFileSync('vo/durations.json', 'utf8')); // seconds per scene incl. padding
const out = 'clips';
fs.mkdirSync(out, { recursive: true });

const CARD = (title, sub, small = '') => `<html><body style="margin:0;height:100vh;display:flex;flex-direction:column;justify-content:center;align-items:center;background:radial-gradient(circle at 30% 20%,#1f3a2c,#0c1512);color:#eaf2ec;font-family:-apple-system,Helvetica,Arial,sans-serif;text-align:center">
<div style="letter-spacing:.2em;color:#9be29b;font-size:18px;font-weight:700">INSIDE THE GAME</div>
<div style="font-size:64px;font-weight:800;margin:18px 40px">${title}</div>
<div style="font-size:26px;color:#b9c8bd;max-width:1000px;line-height:1.4">${sub}</div>
<div style="font-size:18px;color:#8aa093;margin-top:36px;max-width:1000px;line-height:1.6">${small}</div>
<div style="position:fixed;top:16px;right:20px;font:600 14px sans-serif;color:#ffcf6e;border:1px solid #ffcf6e;border-radius:6px;padding:4px 8px">DRAFT · pre-redesign</div></body></html>`;

async function overlay(page, text, top = false) {
  await page.evaluate(([text, top]) => {
    let o = document.getElementById('__vo');
    if (!o) {
      o = document.createElement('div'); o.id = '__vo';
      o.style.cssText = 'position:fixed;left:50%;bottom:28px;transform:translateX(-50%);z-index:99999;background:rgba(8,14,11,.88);color:#fff;font:700 24px -apple-system,Helvetica,sans-serif;padding:12px 22px;border-radius:10px;border:1px solid #9be29b;max-width:1100px;text-align:center;box-shadow:0 6px 30px rgba(0,0,0,.5)';
      document.body.appendChild(o);
      const d = document.createElement('div');
      d.style.cssText = 'position:fixed;top:12px;right:16px;z-index:99999;font:600 13px sans-serif;color:#ffcf6e;border:1px solid #ffcf6e;border-radius:6px;padding:3px 8px;background:rgba(0,0,0,.6)';
      d.textContent = 'DRAFT · pre-redesign'; document.body.appendChild(d);
    }
    o.innerHTML = text; o.style.bottom = top ? 'auto' : '28px'; o.style.top = top ? '56px' : 'auto';
  }, [text, top]);
}

const click = (page, sel) => page.click(sel);
async function seek(page, t) {
  await page.evaluate((t) => { const s = document.querySelector('#seek'); s.value = t; s.dispatchEvent(new Event('input', { bubbles: true })); s.dispatchEvent(new Event('change', { bubbles: true })); }, t);
}
async function smoothScroll(page, y, ms) {
  await page.evaluate(([y, ms]) => new Promise(r => { const y0 = scrollY, t0 = performance.now(); const f = (n) => { const k = Math.min(1, (n - t0) / ms); scrollTo(0, y0 + (y - y0) * (k < .5 ? 2 * k * k : 1 - (-2 * k + 2) ** 2 / 2)); k < 1 ? requestAnimationFrame(f) : r(); }; requestAnimationFrame(f); }), [y, ms]);
}
async function live(page, { lang = 'en', profile = 'casual', player = '', at = 0, speed = '2' } = {}) {
  await page.goto(BASE, { waitUntil: 'networkidle' });
  await page.waitForSelector('#seek');
  if (profile !== 'casual') await click(page, `#profile button[data-v=${profile}]`);
  if (lang !== 'en') await click(page, `#lang button[data-v=${lang}]`);
  if (player) await page.selectOption('#player', player);
  await click(page, `#speed button[data-v="${speed}"]`);
  await seek(page, at);
  await page.evaluate(() => scrollTo(0, document.querySelector('#pitch').getBoundingClientRect().top + scrollY - 120));
}
const wait = (page, s) => page.waitForTimeout(s * 1000);

const scenes = [
  async (page, d) => { await page.setContent(CARD('One match. Every fan.', 'Fact-checked live commentary, personalised for every viewer.')); return async () => wait(page, d); },
  async (page, d) => { await page.goto(BASE, { waitUntil: 'networkidle' }); await overlay(page, 'Casual or analyst · English or 中文 · your club · your player'); return async () => { await wait(page, 2); await page.hover('#profile button[data-v=analyst]'); await wait(page, 1.5); await page.hover('#lang button[data-v=zh]'); await wait(page, 1.5); await page.hover('#follow'); await wait(page, 1.5); await page.hover('#player'); await wait(page, d - 6.5); }; },
  async (page, d) => { await live(page, { at: 186 }); await overlay(page, 'Two voices: instant play-by-play + agent analysis'); return async () => { await click(page, '#play'); await wait(page, d); }; },
  async (page, d) => { await live(page, { at: 66 }); await overlay(page, 'Casual: the story'); return async () => { await click(page, '#play'); await wait(page, d * .45); await click(page, '#profile button[data-v=analyst]'); await overlay(page, 'Analyst: the numbers'); await wait(page, d * .55); }; },
  async (page, d) => { await live(page, { at: 392, lang: 'zh' }); await overlay(page, 'Simplified Chinese, generated by the same workflow'); return async () => { await click(page, '#play'); await wait(page, d); }; },
  async (page, d) => { await live(page, { at: 462, player: 'a9' }); await overlay(page, 'Player focus: #10 Callum Ashby (fictional)'); return async () => { await click(page, '#play'); await wait(page, d); }; },
  async (page, d) => { await page.goto(BASE, { waitUntil: 'networkidle' }); await overlay(page, 'Microsoft Agent Framework workflow · rejected lines loop back to the narrator', true); return async () => { const y = await page.evaluate(() => document.body.scrollHeight - innerHeight); await smoothScroll(page, y, 2500); await wait(page, d - 2.5); }; },
  async (page, d) => { await live(page, { at: 96, speed: '1' }); await overlay(page, 'Measured, not simulated: ~9 s median per analysis line (local 9B model)'); return async () => { await click(page, '#play'); await wait(page, d * .5); await overlay(page, '102 of 108 lines agent-written and passed both checks · 6 template fallbacks'); await wait(page, d * .5); }; },
  async (page, d) => { await page.goto(BASE + 'studio.html?match=remix-42', { waitUntil: 'networkidle' }); await wait(page, 1); await overlay(page, 'Post-match studio: six storylines from full-match stats'); return async () => { await wait(page, 1.5); const y = await page.evaluate(() => document.body.scrollHeight - innerHeight); await smoothScroll(page, Math.min(y, 2600), (d - 2.5) * 1000); await wait(page, 1); }; },
  async (page, d) => { await page.setContent(CARD('Inside the Game', 'One match. Every fan.', 'Synthetic matches stitched from DFL open data (CC BY 4.0) · fictional clubs and players<br>Microsoft Agent Framework<br>github.com/Wichai-pan/inside-the-game · wichai-pan.github.io/inside-the-game')); return async () => wait(page, d); },
];

const browser = await chromium.launch({ channel: 'chrome' });
const offsets = [];
for (let i = 0; i < scenes.length; i++) {
  const ctx = await browser.newContext({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  const t0 = Date.now();
  const run = await scenes[i](page, dur[i]);
  offsets.push((Date.now() - t0) / 1000);
  const dir = `${out}/scene${i + 1}`; fs.rmSync(dir, { recursive: true, force: true }); fs.mkdirSync(dir);
  let going = true; const shots = []; const c0 = Date.now();
  const loop = (async () => { while (going) { const t = (Date.now() - c0) / 1000; const p = `${dir}/${String(shots.length).padStart(5, '0')}.jpg`; await page.screenshot({ path: p, type: 'jpeg', quality: 85 }); shots.push([p, t]); } })();
  await run(); going = false; await loop;
  const end = (Date.now() - c0) / 1000;
  let cc = 'ffconcat version 1.0\n';
  shots.forEach(([p, t], k) => { const next = k + 1 < shots.length ? shots[k + 1][1] : end; cc += `file '${p.split('/').pop()}'\nduration ${(next - t).toFixed(3)}\n`; });
  cc += `file '${shots.at(-1)[0].split('/').pop()}'\n`;
  fs.writeFileSync(`${dir}/frames.txt`, cc);
  console.log('frames', shots.length, 'over', end.toFixed(1), 's');
  await ctx.close();
  console.log('scene', i + 1, 'setup', offsets[i].toFixed(2), 's');
}
fs.writeFileSync(`${out}/offsets.json`, JSON.stringify(offsets));
await browser.close();
